def test_prerequisite_detection_reports_missing_humanize_side_docs_even_when_repo_docs_exist(tmp_path):
    bridge = load_bridge_module()
    isolated_repo = tmp_path / "isolated" / "rl-infra-design-agents"
    (isolated_repo / "integrations" / "humanize").mkdir(parents=True)
    (isolated_repo / "docs").mkdir()
    (isolated_repo / "integrations" / "humanize" / "README.md").write_text("repo humanize docs\n", encoding="utf-8")
    (isolated_repo / "docs" / "humanize-compatible-rlcr.md").write_text("repo rlcr docs\n", encoding="utf-8")
    (isolated_repo / "CLAUDE.md").write_text("repo claude docs\n", encoding="utf-8")

    prereqs = bridge.detect_prerequisites(isolated_repo, env={}, path="")

    assert prereqs["humanize_roots"] == []
    assert prereqs["humanize_instruction_files"] == []
    assert len(prereqs["repository_instruction_files"]) == 3
    assert prereqs["codex_cli"] is None
    assert any("Humanize root not found" in warning for warning in prereqs["warnings"])
    assert any("codex CLI not found" in warning for warning in prereqs["warnings"])
    assert any("Humanize-side Claude Code/Humanize instruction files" in warning for warning in prereqs["warnings"])


def test_truncate_stream_marks_long_output():
    bridge = load_bridge_module()
    short_text, short_truncated = bridge.truncate_stream("short output")
    assert short_text == "short output"
    assert short_truncated is False

    long_text, long_truncated = bridge.truncate_stream("x" * (bridge.MAX_COMMAND_OUTPUT_CHARS + 10))
    assert long_truncated is True
    assert long_text.startswith("x" * bridge.MAX_COMMAND_OUTPUT_CHARS)
    assert f"truncated to {bridge.MAX_COMMAND_OUTPUT_CHARS} characters" in long_text


def test_target_repo_status_warns_for_non_git_and_bad_diff_base(tmp_path):
    bridge = load_bridge_module()
    non_git = tmp_path / "non-git"
    non_git.mkdir()

    status, warnings = bridge.target_repo_status(non_git, "main")
    assert status["provided"] is True
    assert status["is_git_repo"] is False
    assert any("not a git repository" in warning or "git is unavailable" in warning for warning in warnings)

    git_repo = tmp_path / "git-repo"
    git_repo.mkdir()
    init = subprocess.run(["git", "init"], cwd=git_repo, text=True, capture_output=True)
    if init.returncode != 0:
        pytest.skip("git init unavailable in this test environment")

    status, warnings = bridge.target_repo_status(git_repo, "no-such-branch")
    assert status["is_git_repo"] is True
    assert status["diff_base_resolves"] is False
    assert any("diff base does not resolve" in warning for warning in warnings)
