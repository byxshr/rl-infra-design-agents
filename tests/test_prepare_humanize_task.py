from __future__ import annotations

import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest


ROOT = Path(__file__).resolve().parents[1]
PREPARE = ROOT / "scripts" / "prepare_humanize_task.py"
CONTRACT = ROOT / "examples" / "task_contracts" / "training-rollout-mismatch-debug.yaml"


def no_codex_env() -> dict[str, str]:
    env = dict(os.environ)
    env["PATH"] = ""
    env.pop("HUMANIZE_ROOT", None)
    return env


def run_prepare(args: list[str], *, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(PREPARE), *args],
        cwd=ROOT,
        text=True,
        capture_output=True,
        env=env,
    )


def load_bridge_module():
    spec = importlib.util.spec_from_file_location("prepare_humanize_task", PREPARE)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_prepare_humanize_task_creates_humanize_ready_workspace_with_warnings(tmp_path):
    workspace = tmp_path / "workspace"
    target_repo = tmp_path / "target-repo"
    target_repo.mkdir()

    result = run_prepare(
        [
            "--contract",
            str(CONTRACT),
            "--workspace",
            str(workspace),
            "--target-repo",
            str(target_repo),
            "--diff-base",
            "main",
            "--force",
            "--overwrite-human-docs",
        ],
        env=no_codex_env(),
    )

    assert result.returncode == 0, result.stdout + result.stderr
    assert "WARN: codex CLI not found" in result.stdout

    start = workspace / "humanize_start.md"
    metadata_path = workspace / ".humanize" / "rlinfra_bridge.json"
    plan_lock = workspace / ".humanize" / "plan.lock.md"
    assert start.exists()
    assert metadata_path.exists()
    assert plan_lock.exists()

    start_text = start.read_text(encoding="utf-8")
    assert f"Workspace path: `{workspace.resolve()}`" in start_text
    assert f"Contract path: `{CONTRACT.resolve()}`" in start_text
    assert f"Target repo: `{target_repo.resolve()}`" in start_text
    assert "Diff base: `main`" in start_text
    assert "Do **not** launch Claude Code" in start_text
    assert "launch_humanize.sh" in start_text
    assert "git add -f .humanize" in start_text
    assert "generated by scripts/prepare_humanize_task.py" in start_text
    assert "Main repo commit:" in start_text
    assert "Pinned RLInfraWiki commit:" in start_text
    assert "Preserve RLInfraWiki page IDs and source IDs" in start_text
    assert "source-reported" in start_text
    assert "docs/validation_matrix.md" in start_text
    assert "docs/risk_register.md" in start_text

    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    assert metadata["schema_version"] == 2
    assert metadata["execution_mode"] == "target_repo"
    assert metadata["repo_commit"] is None
    assert metadata["rlinfrawiki_commit"] is None
    assert metadata["contract"] == str(CONTRACT.resolve())
    assert metadata["workspace"] == str(workspace.resolve())
    assert metadata["target_repo"] == str(target_repo.resolve())
    assert metadata["target_repo_status"]["path"] == str(target_repo.resolve())
    assert metadata["diff_base"] == "main"
    assert metadata["plan_lock"] == str(plan_lock.resolve())
    assert metadata["humanize_start"] == str(start.resolve())
    assert metadata["next_command"] is None
    assert set(metadata["context_paths"]) == {"markdown", "json", "sources"}
    assert "humanize_instruction_files" in metadata["prerequisites"]
    assert "repository_instruction_files" in metadata["prerequisites"]
    assert any("codex CLI not found" in warning for warning in metadata["prereq_warnings"])
    assert any("git CLI not found" in warning for warning in metadata["prereq_warnings"])
    assert [row["name"] for row in metadata["commands_run"]] == [
        "render_task_bundle",
        "validate_context_bundle",
        "lock_plan",
        "validate_review_gate",
    ]
    for row in metadata["commands_run"]:
        assert "timeout_seconds" in row
        assert "stdout_truncated" in row
        assert "stderr_truncated" in row

    for rel_path in [
        "context/context_bundle.md",
        "context/context_bundle.json",
        "context/context_sources.yaml",
    ]:
        assert (workspace / rel_path).exists(), rel_path


